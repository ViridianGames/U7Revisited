--- Global constants and flags for U7Revisited
--- This file is loaded before all other scripts to provide common constants
---
--- FLAG NUMBERS are verified against usecode.dc (the shipped-binary decompile).
--- Names are taken from Docs/U7-Code-Useable Index and Flags where they match,
--- plus first-meet heuristics (FLAG_MET_*) and hand-verified quest flags.
---
--- WARNING: The PDF index numbers for many towns are a pre-ship layout and do
--- NOT match the final game. Always use the constants here, never raw PDF indices.
---
--- Flags that appear in usecode but are not yet named are intentionally omitted
--- so we never attach a wrong semantic label (which would cause collisions later).

function table.find(t, val)
    for i, v in ipairs(t) do
        if v == val then return i end
    end
    return nil
end

function table.contains(t, val)
    return table.find(t, val) ~= nil
end

